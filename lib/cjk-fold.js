function buildCharMap(pairsStr) {
  const map = Object.create(null);
  for (const tok of String(pairsStr).split(/\s+/)) {
    if (!tok) continue;
    const chars = [...tok];
    if (chars.length !== 2) continue;
    map[chars[0]] = chars[1];
  }
  // Finance / scam-copy overrides.
  map['帳'] = '账';
  map['賬'] = '账';
  map['戶'] = '户';
  map['髮'] = '发';
  map['發'] = '发';
  map['後'] = '后';
  map['裡'] = '里';
  map['裏'] = '里';
  map['臺'] = '台';
  map['麵'] = '面';
  map['乾'] = '干';
  map['係'] = '系';
  map['麼'] = '么';
  map['麽'] = '么';
  return map;
}

const T2S = buildCharMap(T2S_PAIRS);

function foldTraditionalToSimplified(text) {
  let out = text == null ? '' : String(text);
  for (const [from, to] of PHRASES) {
    if (out.includes(from)) out = out.split(from).join(to);
  }
  let folded = '';
  for (const ch of out) {
    folded += T2S[ch] || ch;
  }
  return folded;
}

function normalizeForMatch(text, maxLen = 2000) {
  if (text == null) return '';
  let s = String(text).normalize('NFKC').trim().slice(0, maxLen);
  s = foldTraditionalToSimplified(s);
  s = s.toLowerCase();
  s = s.replace(/https?:\/\/[^\s]+/gi, ' httpurl ');
  s = s.replace(/[^\p{L}\p{N}]+/gu, ' ');
  s = s.replace(/\s+/g, ' ').trim();
  return s;
}

